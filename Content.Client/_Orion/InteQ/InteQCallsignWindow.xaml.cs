using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Orion.InteQ;

[GenerateTypedNameReferences]
public sealed partial class InteQCallsignWindow : FancyWindow
{
    public Action<string>? OnSetName;
    public Action? OnRandomName;

    public InteQCallsignWindow()
    {
        RobustXamlLoader.Load(this);

        NameSetButton.OnPressed += _ => OnSetName?.Invoke(NameSelector.Text);
        RandomButton.OnPressed += _ => OnRandomName?.Invoke();
        NameSelector.OnTextEntered += _ => OnSetName?.Invoke(NameSelector.Text);
    }

    public void UpdateState(string name)
    {
        NameSelector.Text = name;
    }
}
